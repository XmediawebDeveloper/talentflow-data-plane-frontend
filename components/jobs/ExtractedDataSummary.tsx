'use client';

import { useState, type ReactNode } from 'react';
import { BarChart3, Briefcase, CheckCircle, ChevronRight, MapPin, Sparkles, Wand2, X, type LucideIcon } from 'lucide-react';
import { EXPERIENCE_LEVEL_ONLY_NOTE, EXPERIENCE_YEARS_NOT_STATED } from '@/lib/utils/jobExperience';
import { STEP2_CARD_CLASS, STEP2_SECTION_TONES, Step2SectionHeader } from '@/components/jobs/Step2Section';

/*
 * The "Extracted Data Summary" as the JD wizard's Review step draws it - the
 * one format every surface uses.
 *
 * The building blocks (card + toggle header, section heading, ticked list,
 * field tiles) are exported for the Review step itself, which adds Edit links
 * and its own editable fields. Read-only pages render the whole summary with
 * the default export, passing their own data and labels.
 */

export const SUMMARY_FIELD_LABEL = 'text-sm text-gray-600 dark:text-slate-400 mb-1 sm:mb-2';
export const SUMMARY_FIELD_VALUE = 'text-sm sm:text-base text-gray-900 dark:text-slate-50 [overflow-wrap:anywhere]';
export const SUMMARY_EMPTY_VALUE = 'text-sm text-gray-500 dark:text-slate-500 italic';
export const SUMMARY_TILE = 'min-w-0 bg-gray-50 dark:bg-slate-800/50 p-3 sm:p-4 rounded-lg';
export const SUMMARY_NOTE = 'text-xs text-gray-500 dark:text-slate-500 mt-1';
export const SUMMARY_LIST_HEADING = 'text-sm text-gray-700 dark:text-slate-300 mb-3';

/** The card, its whole-row toggle header and the divided body. */
export function ExtractedSummaryCard({
  open,
  onToggle,
  aiExtracted = false,
  children,
}: {
  open: boolean;
  onToggle: () => void;
  /** Shows the "AI Extracted" badge (a JD generated by AI). */
  aiExtracted?: boolean;
  children: ReactNode;
}) {
  return (
    <div className={STEP2_CARD_CLASS}>
      <button
        type="button"
        onClick={onToggle}
        aria-expanded={open}
        className="w-full text-left rounded-lg"
      >
        <Step2SectionHeader
          icon={BarChart3}
          tone="orange"
          spacing="mb-0"
          inlineActions
          title="Extracted Data Summary"
          hint={`Click to ${open ? 'hide' : 'view'} structured requirements`}
          badge={aiExtracted ? (
            <span className="tf-badge bg-brand-cyan/10 text-brand-cyan ring-1 ring-brand-cyan/20">
              <Wand2 className="w-3 h-3" />
              AI Extracted
            </span>
          ) : undefined}
          actions={
            <span className={`inline-flex transform transition-transform ${open ? 'rotate-180' : ''}`}>
              <ChevronRight className="w-5 h-5 text-gray-500 dark:text-slate-500 rotate-90" />
            </span>
          }
        />
      </button>
      {open && (
        <div className="mt-4 sm:mt-5 pt-1 border-t border-gray-100 dark:border-slate-700/60 divide-y divide-gray-100 dark:divide-slate-700/60">
          {children}
        </div>
      )}
    </div>
  );
}

/** A section's heading row: toned icon + title, `actions` at the right end
 *  (the Review step's Edit link). */
export function SummarySectionHeading({
  icon: Icon,
  tone,
  title,
  actions,
}: {
  icon: LucideIcon;
  tone: keyof typeof STEP2_SECTION_TONES;
  title: string;
  actions?: ReactNode;
}) {
  return (
    <div className="flex items-center justify-between gap-3 mb-3 sm:mb-4">
      <h3 className="flex items-center gap-2 tf-row-title sm:text-base">
        <Icon className={`w-4 h-4 flex-shrink-0 ${STEP2_SECTION_TONES[tone].icon}`} />
        {title}
      </h3>
      {actions}
    </div>
  );
}

/** One section under the summary's dividers: heading, then content.
 *  `last` drops the bottom padding, as the final section does on the Review step. */
export function SummarySection({
  icon,
  tone,
  title,
  actions,
  last = false,
  children,
}: {
  icon: LucideIcon;
  tone: keyof typeof STEP2_SECTION_TONES;
  title: string;
  actions?: ReactNode;
  last?: boolean;
  children: ReactNode;
}) {
  return (
    <div className={last ? 'pt-4 sm:pt-5' : 'py-4 sm:py-5'}>
      <SummarySectionHeading icon={icon} tone={tone} title={title} actions={actions} />
      {children}
    </div>
  );
}

/** A skills / requirements list: a green tick per line, or the empty message. */
export function SummaryItemList({ items, emptyMessage = 'None added' }: { items: string[]; emptyMessage?: string }) {
  return items.length > 0 ? (
    <div className="space-y-2">
      {items.map((item, index) => (
        <div key={index} className="flex items-start gap-2 tf-body">
          <CheckCircle className="w-4 h-4 text-success flex-shrink-0 mt-0.5" />
          <span className="min-w-0 [overflow-wrap:anywhere]">{item}</span>
        </div>
      ))}
    </div>
  ) : (
    <p className={SUMMARY_EMPTY_VALUE}>{emptyMessage}</p>
  );
}

/** The Allow Over-Qualified value, ticked or crossed as on the Review step. */
export function SummaryYesNo({ value }: { value: boolean }) {
  return (
    <p className={`${SUMMARY_FIELD_VALUE} flex items-center gap-1.5`}>
      {value
        ? <CheckCircle className="w-4 h-4 text-success flex-shrink-0" />
        : <X className="w-4 h-4 text-gray-400 dark:text-slate-500 flex-shrink-0" />}
      {value ? 'Yes' : 'No'}
    </p>
  );
}

export interface ExtractedDataSummaryProps {
  mustHaveSkills: string[];
  niceToHaveSkills: string[];
  mustHaveComments: string[];
  niceToHaveComments: string[];
  /** The "✓ Required (Essential)" / "○ Preferred" labels on the two
   *  requirement lists (shown only while a list has lines). */
  showRequirementBadges?: boolean;
  /** The experience value as the page words it; empty → "Not specified". */
  experience?: string | null;
  /** Line under Experience (its Required / Preferred label). */
  experienceNote?: string;
  /** The JD's level name ("Senior Level") when it has a level but NO years
   *  stored. Shown in place of "Not specified", flagged as level-only, so the
   *  tile agrees with the header badge instead of contradicting it. */
  experienceLevelOnly?: string | null;
  /** Industry label; the tile is shown only when there is one. */
  industry?: string | null;
  industryNote?: string;
  /** Location text; the tile is shown only when there is one. Used as a
   *  fallback when `locations` below is absent/empty. */
  location?: string | null;
  locationNote?: string;
  /** Every saved location (city/state/country/radius_km), rendered one chip
   *  per entry with its radius. Takes priority over `location` when non-empty,
   *  since `location` alone cannot distinguish "one city" from "first of many". */
  locations?: Array<{ city?: string | null; radius_km?: number | null }> | null;
  /** Already-labelled values ("Full Time", "Hybrid", "Not specified"). */
  employmentType: string;
  workMode: string;
  /**
   * The recruiter's scoring answers. Omit to leave them out (a quick read of
   * the JD rather than a review of how resumes are graded).
   */
  scoring?: {
    allowOverqualified?: boolean | null;
    jobHoppingEnabled?: boolean | null;
    /** The page's wording for "No" over-qualified candidates. */
    overqualifiedNoNote: string;
  };
  aiExtracted?: boolean;
  /** Collapsed by default, as on the Review step. */
  defaultOpen?: boolean;
}

/** The read-only Extracted Data Summary, in the Review step's format. */
export default function ExtractedDataSummary({
  mustHaveSkills,
  niceToHaveSkills,
  mustHaveComments,
  niceToHaveComments,
  showRequirementBadges = true,
  experience,
  experienceNote,
  experienceLevelOnly,
  industry,
  industryNote,
  location,
  locationNote,
  locations,
  employmentType,
  workMode,
  scoring,
  aiExtracted = false,
  defaultOpen = false,
}: ExtractedDataSummaryProps) {
  const locationChips = (locations || []).filter((loc) => loc.city);
  const [open, setOpen] = useState(defaultOpen);

  return (
    <ExtractedSummaryCard open={open} onToggle={() => setOpen((v) => !v)} aiExtracted={aiExtracted}>
      <SummarySection icon={Sparkles} tone="blue" title="Skills & Requirements">
        <div className="tf-grid-2">
          <div className="min-w-0">
            <h4 className={SUMMARY_LIST_HEADING}>Must-Have Skills ({mustHaveSkills.length})</h4>
            <SummaryItemList items={mustHaveSkills} />
          </div>
          <div className="min-w-0">
            <h4 className={SUMMARY_LIST_HEADING}>Nice-to-Have Skills ({niceToHaveSkills.length})</h4>
            <SummaryItemList items={niceToHaveSkills} />
          </div>
          <div className="min-w-0">
            {/* Labelled Essential/Preferred because these two lists are where a
                degree requirement lands - Education has no tile of its own. Only
                while the list HAS lines: the badge is a claim about scoring. */}
            <h4 className={SUMMARY_LIST_HEADING}>
              Must-Have Additional Requirements ({mustHaveComments.length})
              {showRequirementBadges && mustHaveComments.length > 0 && (
                <span className="ml-2 text-xs font-normal text-gray-500 dark:text-slate-500">✓ Required (Essential)</span>
              )}
            </h4>
            <SummaryItemList items={mustHaveComments} />
          </div>
          <div className="min-w-0">
            <h4 className={SUMMARY_LIST_HEADING}>
              Nice-to-Have Additional Requirements ({niceToHaveComments.length})
              {showRequirementBadges && niceToHaveComments.length > 0 && (
                <span className="ml-2 text-xs font-normal text-gray-500 dark:text-slate-500">○ Preferred</span>
              )}
            </h4>
            <SummaryItemList items={niceToHaveComments} />
          </div>
        </div>
      </SummarySection>

      <SummarySection icon={Briefcase} tone="success" title="Role Requirements">
        <div className="tf-grid-2">
          <div className={SUMMARY_TILE}>
            <h4 className={SUMMARY_FIELD_LABEL}>Experience</h4>
            {experience ? (
              <>
                <p className={SUMMARY_FIELD_VALUE}>{experience}</p>
                {experience.includes(EXPERIENCE_YEARS_NOT_STATED) && (
                  <p className="text-xs text-amber-700 dark:text-amber-400 mt-1">{EXPERIENCE_LEVEL_ONLY_NOTE}</p>
                )}
              </>
            ) : experienceLevelOnly ? (
              <>
                <p className={SUMMARY_FIELD_VALUE}>{experienceLevelOnly}</p>
                <p className="text-xs text-amber-700 dark:text-amber-400 mt-1">{EXPERIENCE_LEVEL_ONLY_NOTE}</p>
              </>
            ) : (
              <p className={SUMMARY_EMPTY_VALUE}>Not specified</p>
            )}
            {(experience || experienceLevelOnly) && experienceNote && <p className={SUMMARY_NOTE}>{experienceNote}</p>}
            {scoring && (
              <p className={SUMMARY_NOTE}>
                Evaluate Job Hopping: {scoring.jobHoppingEnabled === null || scoring.jobHoppingEnabled === undefined
                  ? 'Not specified'
                  : scoring.jobHoppingEnabled ? 'Yes' : 'No'}
              </p>
            )}
          </div>
          {industry && (
            <div className={SUMMARY_TILE}>
              <h4 className={SUMMARY_FIELD_LABEL}>Industry Type</h4>
              <p className={SUMMARY_FIELD_VALUE}>{industry}</p>
              {industryNote && <p className={SUMMARY_NOTE}>{industryNote}</p>}
            </div>
          )}
          {scoring && (
            <div className={SUMMARY_TILE}>
              <h4 className={SUMMARY_FIELD_LABEL}>Allow Over-Qualified Candidates</h4>
              {scoring.allowOverqualified === null || scoring.allowOverqualified === undefined
                ? <p className={SUMMARY_EMPTY_VALUE}>Not specified</p>
                : <SummaryYesNo value={scoring.allowOverqualified} />}
              <p className={SUMMARY_NOTE}>
                {scoring.allowOverqualified === false
                  ? scoring.overqualifiedNoNote
                  : 'Extra relevant experience is not penalised'}
              </p>
            </div>
          )}
        </div>
      </SummarySection>

      <SummarySection icon={MapPin} tone="cyan" title="Location & Work Setup" last>
        <div className="tf-grid-2">
          {(locationChips.length > 0 || location) && (
            <div className={`${SUMMARY_TILE} sm:col-span-2`}>
              <h4 className={SUMMARY_FIELD_LABEL}>Location</h4>
              <div className="flex flex-wrap gap-2">
                {locationChips.length > 0 ? (
                  locationChips.map((loc, index) => (
                    <span key={index} className="tf-panel inline-flex items-center gap-1.5 max-w-full px-2.5 py-1 tf-body">
                      <MapPin className="w-3.5 h-3.5 text-brand-cyan flex-shrink-0" />
                      <span className="min-w-0 [overflow-wrap:anywhere]">{loc.city}</span>
                      {loc.radius_km != null && (
                        <span className="tf-meta">({loc.radius_km} km radius)</span>
                      )}
                    </span>
                  ))
                ) : (
                  <span className="tf-panel inline-flex items-center gap-1.5 max-w-full px-2.5 py-1 tf-body">
                    <MapPin className="w-3.5 h-3.5 text-brand-cyan flex-shrink-0" />
                    <span className="min-w-0 [overflow-wrap:anywhere]">{location}</span>
                  </span>
                )}
              </div>
              {locationNote && <p className={SUMMARY_NOTE}>{locationNote}</p>}
            </div>
          )}
          <div className={SUMMARY_TILE}>
            <h4 className={SUMMARY_FIELD_LABEL}>Employment Type</h4>
            <p className={SUMMARY_FIELD_VALUE}>{employmentType}</p>
          </div>
          <div className={SUMMARY_TILE}>
            <h4 className={SUMMARY_FIELD_LABEL}>Work Mode</h4>
            <p className={SUMMARY_FIELD_VALUE}>{workMode}</p>
          </div>
        </div>
      </SummarySection>
    </ExtractedSummaryCard>
  );
}
